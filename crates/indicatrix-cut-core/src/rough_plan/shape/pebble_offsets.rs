//! The pinned plane offsets of the pebble's unit polytope.
//!
//! The pebble is the polytope `{ u : d_j . u <= h_j }` over the geodesic directions `d_j` of
//! [`sampling::pebble_directions`](super::sampling::pebble_directions), mapped linearly onto
//! the inscribed ellipsoid. The offsets `h_j` are the fixed point of this iteration: start
//! with every `h_j = 1`; measure the polytope; for every face take the largest radius
//! `r_j` among the vertices lying on its plane (`|d_j . v - h_j| < 1e-9`), or 1 if it has
//! none; replace `h_j` by `h_j / r_j`; repeat until every `r_j` is within `1e-12` of 1; then
//! shrink all offsets by the largest vertex radius so every vertex lies inside the unit
//! ball. Each face is thereby pushed out until its own vertices touch the unit sphere,
//! which holds more of the ball than one global shrink of an `{ h_j = 1 }` polytope.
//!
//! The tables are pinned so the pebble is the same on every machine and run. To regenerate
//! them run
//! `cargo test --release -p indicatrix-cut-core -- regenerate_pebble_offsets --ignored --nocapture`
//! and paste the printed arrays over the constants below.

