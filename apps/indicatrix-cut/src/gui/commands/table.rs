//! The command table: every action the palette can run.
//!
//! **Adding a command is one entry in [`COMMANDS`].** Give it a unique `id`, the name users
//! already know from the menu or button, a few search keywords, its key combination if it
//! has one (it must also be a row of `gui::editor::shortcuts::SHORTCUTS`), the checks that
//! decide when it is available, and what it runs. The palette, its search, its disabled
//! reasons and the guide locks all come from the entry; nothing else needs touching.
//!
//! A command runs the same Slint callback or property its menu item or button uses. Put the
//! guide's lock first in `requires`, so a locked command always says "Locked by the guide".

