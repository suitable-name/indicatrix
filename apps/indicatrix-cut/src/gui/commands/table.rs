/// A run action that invokes one callback of a global: `call!(EditorModel.invoke_undo)`.
macro_rules! call {
    ($model:ident . $method:ident) => {
        |ui: &MainWindow| {
            ui.global::<crate::$model>().$method();
        }
    };
}

/// A run action that sets one property of a global: `set!(ShortcutsModel.set_open(true))`.
macro_rules! set {
    ($model:ident . $method:ident ( $value:expr )) => {
        |ui: &MainWindow| {
            ui.global::<crate::$model>().$method($value);
        }
    };
}

